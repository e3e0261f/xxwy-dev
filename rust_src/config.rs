//! # config.rs - 青城 (Qk) 修仙大世界参数控制中心
//!
//! ## 架构设计铁律
//! 根据《青城修仙大世界项目技术白皮书》开发准则：
//! **绝对禁止硬编码**。坐标、速度、几率、瓦片尺寸等所有全局参数，必须集中在此定义。
//! 每一个常量均附带详尽的中文设计动机说明，解释“为什么设定该数值”。

use bevy::prelude::*;

/// 瓦片渲染物理尺寸 (以像素为基准)
/// 为什么设定为 64.0？
/// 因为美术手绘资源采用 64x64 高清像素规格，设为 64.0 能在正交摄像机 1:1 投影下
/// 呈现最清晰的点阵质感，避免缩放采样导致的边缘发糊。
pub const TILE_SIZE: f32 = 64.0;

/// 世界区块瓦片边长 (16 × 16 瓦片为一个 Chunk)
/// 为什么设定为 16？
/// 16 瓦片对应 1024 像素物理跨度，符合 GPU 纹理显存对齐规范；
/// 同时 16x16 是现代 2D 开放世界流式加载的最佳粒度，既不会因区块过小产生高频 IO，
/// 也不会因区块过大导致跨区块加载时的卡顿。
pub const CHUNK_SIZE: i32 = 16;

/// 激活区块视距半径 (九宫格流式调度，当前区块周围半径为 1，即 3×3 = 9 个区块)
/// 为什么仅保留 9 个区块？
/// 保证内存占用恒定 (O(1))，无论玩家跑动多远，显存内只驻留视野周围九个区块，
/// 其余离开视野的区块立即触发 Despawn 垃圾回收。
pub const ACTIVE_CHUNK_RADIUS: i32 = 1;

/// 摄像机平滑跟随系数 (Lerp 平滑阻尼)
/// 为什么采用 0.08 而非硬锁定？
/// 0.08 的缓动能带来道法自然的飘逸运镜感，模拟修仙者御气凌风时的惯性视线。
pub const CAMERA_LERP_FACTOR: f32 = 0.08;

/// 摄像机正交投影缩放比 (正交 2D 比例)
pub const CAMERA_ORTHO_SCALE: f32 = 0.85;

/// 玩家基础移动速度 (像素/秒)
/// 为什么是 190.0？
/// 经测算，190 像素/秒约相当于每秒穿行 3 个地表瓦片，符合常人快步与修士行云流水般的移速感。
pub const PLAYER_BASE_SPEED: f32 = 190.0;

/// 玩家八向移动斜向归一化补偿
/// 为什么需要归一化？
/// 欧氏距离下斜向速度为 √2 ≈ 1.414 倍，必须归一化以维护公平的移速法则。
pub const DIAGONAL_SPEED_FACTOR: f32 = 0.70710678;

/// 自动入定时间阈值 (秒)
/// 为什么设计为 1.8 秒？
/// 践行“无字化、行为驱动”哲学：玩家停步驻足 1.8 秒后，修士本能引气入体，
/// 自动进入吐纳冥想状态，浮现灵气呼吸光晕，无需多余的点击按钮。
pub const MEDITATION_IDLE_THRESHOLD: f32 = 1.8;

/// 灵气呼吸光晕脉动周期 (秒)
/// 为什么是 3.2 秒？
/// 对应人类深呼吸吐纳的黄金节律 (吸气 1.6s，呼气 1.6s)，营造心斋坐忘的修道共鸣。
pub const QI_BREATH_PERIOD: f32 = 3.2;

/// 灵气光晕最大透明度与半径
pub const QI_AURA_MAX_ALPHA: f32 = 0.65;
pub const QI_AURA_MIN_ALPHA: f32 = 0.15;
pub const QI_AURA_RADIUS: f32 = 56.0;

/// 2.5D 深度 Y-Sort 排序系数
/// 为什么乘以 0.001？
/// Bevy 的 2D 渲染依托 Transform.translation.z 决定前后遮挡。
/// 将脚底 Y 坐标取负并缩放至 [-10.0, 10.0] 区间，保证脚踏实地的下层实体优先遮挡上层实体。
pub const Y_SORT_FACTOR: f32 = 0.001;

/// 图层深度基础基准常量 (Layer Z-Offsets)
/// 严格匹配白皮书图层物理契约：
/// 4-ccdi: 地表层，最低深度
/// 2-dclu: 道路层，仅次于地表
/// 物体与角色: 动态 Y-Sort
/// 1-jmvu 建筑屋顶: 覆盖角色之上，进入触发透明度渐变
pub const Z_LAYER_GROUND: f32 = 0.0;
pub const Z_LAYER_ROAD: f32 = 1.0;
pub const Z_LAYER_OBJECT_BASE: f32 = 10.0;
pub const Z_LAYER_ROOF: f32 = 50.0;

/// 屋顶半透明过渡参数
/// 为什么进入建筑时淡化至 0.35？
/// 既能让玩家清晰看清室内空间和蒲团陈设，又能保留建筑物屋顶瓦当的轮廓轮廓。
pub const ROOF_FADE_ALPHA: f32 = 0.35;
pub const ROOF_FADE_SPEED: f32 = 4.5;

